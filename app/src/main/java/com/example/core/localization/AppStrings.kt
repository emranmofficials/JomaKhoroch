/**
 * Returns a clean single-language display name for default/seeded account books
 * (including legacy bilingual names like "ব্যক্তিগত (Personal)") while preserving
 * user-created custom book names verbatim.
 */
fun localizedBookName(rawName: String?, type: String?, language: AppLanguage): String {
    val trimmed = rawName?.trim().orEmpty()
    val isDefaultPersonal = trimmed.isEmpty() ||
        trimmed.equals("ব্যক্তিগত (Personal)", ignoreCase = true) ||
        trimmed == "ব্যক্তিগত" ||
        trimmed == "ব্যক্তিগত খাতা" ||
        trimmed.equals("Personal", ignoreCase = true) ||
        trimmed.equals("Personal Book", ignoreCase = true)
    val isDefaultFamily = trimmed.equals("পারিবারিক (Family)", ignoreCase = true) ||
        trimmed == "পারিবারিক" ||
        trimmed == "পারিবারিক খাতা" ||
        trimmed.equals("Family", ignoreCase = true) ||
        trimmed.equals("Family Book", ignoreCase = true)
    val isDefaultBusiness = trimmed.equals("ব্যবসা (Business)", ignoreCase = true) ||
        trimmed == "ব্যবসা" ||
        trimmed == "ব্যবসার খাতা" ||
        trimmed.equals("Business", ignoreCase = true) ||
        trimmed.equals("Business Book", ignoreCase = true)

    return when {
        isDefaultPersonal -> if (language == AppLanguage.BANGLA) "ব্যক্তিগত খাতা" else "Personal Book"
        isDefaultFamily -> if (language == AppLanguage.BANGLA) "পারিবারিক খাতা" else "Family Book"
        isDefaultBusiness -> if (language == AppLanguage.BANGLA) "ব্যবসার খাতা" else "Business Book"
        else -> trimmed
    }
}
